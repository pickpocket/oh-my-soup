#!/usr/bin/env bun
/**
 * Build the self-contained HTML export viewer, including Markdown, highlighting,
 * and shared React tool/trace views. Local `bun run gen:export-viewer` updates
 * viewer.generated.json; CI and `--check` verify it instead, and `--write`
 * updates it even under CI=true. No viewer assets need to be hosted.
 */
import * as fs from "node:fs/promises";
import * as path from "node:path";
import { isDeepStrictEqual } from "node:util";
import { exportThemeStyles, webExportThemeVars } from "../../coding-agent/src/export/html/web-palette";

const viewsDir = path.join(import.meta.dir, "..");
const agentDir = path.join(viewsDir, "../coding-agent");
const htmlDir = path.join(agentDir, "src/export/html");

/** Exact viewer bytes and their content-addressed identity, embedded in every export. */
export interface ExportViewerMetadata {
	file: string;
	integrity: string;
	size: number;
	source: string;
}

/** Build output locations and metadata verification policy for CI or local generation. */
export interface ExportViewerBuildOptions {
	/** Defaults to coding-agent/export-assets. A custom directory also isolates metadata. */
	outDir?: string;
	/** Defaults to the committed source manifest, or outDir/viewer.generated.json for a custom outDir. */
	metadataPath?: string;
	/** Verify existing metadata without rewriting it; mismatches fail before writing output. */
	check?: boolean;
}

/** Generate one exact-byte-hashed viewer asset and its self-contained runtime manifest. */
export async function buildExportViewer(options: ExportViewerBuildOptions = {}): Promise<ExportViewerMetadata> {
	const outDir = options.outDir ?? path.join(agentDir, "export-assets");
	const metadataPath = options.metadataPath ?? path.join(options.outDir ?? htmlDir, "viewer.generated.json");
	const result = await Bun.build({
		entrypoints: [path.join(viewsDir, "src/export-standalone.ts")],
		root: viewsDir,
		target: "browser",
		format: "iife",
		minify: true,
		define: { "process.env.NODE_ENV": JSON.stringify("production") },
	});
	if (!result.success) throw new AggregateError(result.logs, "Export viewer React bundle failed");

	let js = "";
	let css = "";
	for (const artifact of result.outputs) {
		if (artifact.path.endsWith(".css")) css += await artifact.text();
		else if (artifact.path.endsWith(".js")) js += await artifact.text();
		else throw new Error(`Unexpected external export viewer asset: ${artifact.path}`);
	}
	if (!js) throw new Error("Export viewer bundle produced no JavaScript");

	// The fork's share loader imports its authenticated HTTP/VPN crypto backend;
	// bundle it rather than inserting an unresolved ESM import into a classic script.
	const loaderBuild = await Bun.build({
		entrypoints: [path.join(htmlDir, "share-loader.js")],
		target: "browser",
		format: "iife",
		minify: true,
	});
	if (!loaderBuild.success) throw new AggregateError(loaderBuild.logs, "Share loader bundle failed");
	const loaderEntry = loaderBuild.outputs.find(output => output.kind === "entry-point");
	if (!loaderEntry || loaderBuild.outputs.length !== 1) {
		throw new Error("Share loader must produce one self-contained JavaScript entry point");
	}
	const shareLoader = await loaderEntry.text();
	const [shell, templateCss, templateJs, highlight, notice] = await Promise.all(
		["shell.html", "template.css", "template.js", "vendor/highlight.min.js", "vendor/NOTICE"].map(file =>
			Bun.file(path.join(htmlDir, file)).text(),
		),
	);
	const themeCss = exportThemeStyles(webExportThemeVars("dark"), webExportThemeVars("light"));
	// JSON strings preserve arbitrary HTML/CSS without template-literal interpolation.
	// Include the vendored highlighter's license in both the asset and exported HTML.
	// All dependencies execute in this script, with no CDN or runtime import.
	const source = [
		"// Generated by packages/tool-views/scripts/build-export-viewer.ts - DO NOT EDIT",
		`/*\n${notice.replaceAll("*/", "* /")}\n*/`,
		";(function() {",
		"try {",
		highlight,
		";globalThis.hljs = hljs;",
		"const style = document.createElement('style');",
		"style.dataset.omsExportViewer = '';",
		`style.textContent = ${JSON.stringify(`${themeCss}\n${templateCss}\n${css}`)};`,
		// Custom per-export themes already in the head must retain cascade priority.
		"document.head.prepend(style);",
		js,
		";",
		// Register custom elements before mounting the shell or assigning session data.
		"const sessionData = document.getElementById('session-data');",
		"if (!sessionData) throw new Error('Missing session data');",
		"const shell = document.createElement('template');",
		`shell.innerHTML = ${JSON.stringify(shell)};`,
		"sessionData.parentNode.insertBefore(shell.content, sessionData);",
		"if (sessionData.dataset.source === 'share') {",
		shareLoader,
		";}",
		templateJs,
		";document.getElementById('viewer-status')?.remove();",
		"} catch (error) {",
		"const status = document.getElementById('viewer-status');",
		"if (status) status.textContent = 'Failed to load viewer: ' + (error instanceof Error ? error.message : String(error));",
		"}",
		"})();",
		"",
	].join("\n");
	const bytes = Buffer.from(source, "utf8");
	const digest = Bun.SHA256.hash(bytes, "hex");
	const metadata: ExportViewerMetadata = {
		file: `export-viewer-${digest}.js`,
		integrity: `sha256-${Buffer.from(digest, "hex").toBase64()}`,
		size: bytes.length,
		source,
	};

	if (options.check) {
		const existing: unknown = await Bun.file(metadataPath).json();
		if (!isDeepStrictEqual(existing, metadata)) {
			throw new Error(
				"Export viewer metadata is stale; run bun run gen:export-viewer --write (packages/tool-views/scripts/build-export-viewer.ts) and commit viewer.generated.json",
			);
		}
	}
	await fs.mkdir(outDir, { recursive: true });
	await Bun.write(path.join(outDir, metadata.file), bytes);
	if (!options.check) await Bun.write(metadataPath, `${JSON.stringify(metadata, null, "\t")}\n`);
	// Only discard our obsolete content-addressed files, never other build outputs.
	for (const entry of await fs.readdir(outDir, { withFileTypes: true })) {
		if (entry.isFile() && /^export-viewer-[a-f0-9]{64}\.js$/.test(entry.name) && entry.name !== metadata.file) {
			await fs.unlink(path.join(outDir, entry.name));
		}
	}
	return metadata;
}

/**
 * Whether the command line asks to verify rather than update the manifest. CI=true
 * implies a check so installs in CI verify the committed manifest; `--write`
 * overrides that, since shells that export CI=true (oms's bash tool among them)
 * could otherwise never regenerate it. An explicit `--check` always wins.
 */
export function isExportViewerCheck(argv: readonly string[], env: Record<string, string | undefined>): boolean {
	if (argv.includes("--check")) return true;
	return env.CI === "true" && !argv.includes("--write");
}

if (import.meta.main) {
	const metadata = await buildExportViewer({ check: isExportViewerCheck(process.argv, process.env) });
	console.log(`Generated ${metadata.file} (${(metadata.size / 1024).toFixed(1)} KiB)`);
}
